#!/usr/bin/env python3
"""Write THIRD-PARTY.md: every crate the nibcase programs are built from, for nibOS, the stock OS
and the desktop preview, with its licence, and the licence and copyright texts each crate ships,
which go with every copy.

    python3 tools/third_party.py > THIRD-PARTY.md

Reads `cargo metadata` for the handheld's target with each build's features; the crates' own
texts come from cargo's registry and git checkouts (`cargo fetch` first if a source is missing).
Development-only crates (tests, bindgen) are left out: they aren't part of what is shipped.
"""

import json
import subprocess
import sys
from pathlib import Path

TARGET = "aarch64-unknown-linux-gnu"
# The player's features for each build (nibcase-libretro and nibcase-test have none).
BUILDS = {
    "nibos": [],
    "stock": ["--no-default-features", "--features", "nibcase/stock,nibcase/dslot"],
    "desktop": ["--no-default-features", "--features", "nibcase/desktop,nibcase/dslot"],
}
TEXTS = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def graph(flags):
    """The crates the workspace's programs are built from: normal and build dependencies,
    followed from the workspace's members, not dev-dependencies."""
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET, *flags],
        check=True, capture_output=True, text=True).stdout
    meta = json.loads(out)
    members = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, todo = set(), list(members)
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds <= {"dev"} or dep["pkg"] in seen:
                continue
            seen.add(dep["pkg"])
            todo.append(dep["pkg"])
    return [p for p in meta["packages"] if p["id"] in seen - members]


def texts(package):
    """The licence and notice files beside a crate's Cargo.toml, by name."""
    here = Path(package["manifest_path"]).parent
    found = []
    for f in sorted(here.iterdir()):
        if f.is_file() and f.name.upper().startswith(TEXTS):
            found.append((f.name, f.read_text(errors="replace").strip()))
    if package.get("license_file"):
        f = here / package["license_file"]
        if f.is_file() and f.name not in {n for n, _ in found}:
            found.append((f.name, f.read_text(errors="replace").strip()))
    return found


def main():
    crates, used = {}, {}
    for build, flags in BUILDS.items():
        for p in graph(flags):
            crates[p["id"]] = p
            used.setdefault(p["id"], []).append(build)

    rows = sorted(crates.values(), key=lambda p: (p["name"], p["version"]))
    w = sys.stdout.write
    w("# Third-party notices\n\n")
    w("nibcase is MIT (LICENSE). Built into its programs are the crates below, each under its own\n"
      "licence. Their licence and copyright texts follow the list. Generated by\n"
      "`tools/third_party.py`; do not edit.\n\n")
    w("Also in the programs: Roboto Condensed (drawn by nibkit's menu), under the SIL Open Font\n"
      "License 1.1 (third_party/OFL.txt), and libretro.h, the libretro API's header, under the\n"
      "MIT licence (third_party/libretro/libretro.h, its licence at its top). rcheevos, the\n"
      "RetroAchievements library, is built in through nib-cheevos (which vendors it), under the\n"
      "MIT licence (its `rcheevos/LICENSE`, installed as LICENSE.rcheevos). SDL2 is not built\n"
      "in: nibcase links to the system's libSDL2 (zlib licence); RetroAchievements' requests go\n"
      "through the system's `curl` program (curl licence), run, not linked.\n\n")
    w("The libretro cores nibcase plays are separate programs, installed as their own packages\n"
      "under their own licences, and never built into nibcase: docs/systems.md lists them.\n\n")
    w("| Crate | Version | Licence | Built for |\n|---|---|---|---|\n")
    for p in rows:
        lic = p["license"] or f"see {p.get('license_file')}"
        w(f"| {p['name']} | {p['version']} | {lic} | {', '.join(used[p['id']])} |\n")

    # Identical texts (the many copies of the MIT and Apache licences) are printed once, under
    # every crate that ships them.
    by_text = {}
    for p in rows:
        for name, body in texts(p):
            by_text.setdefault(body, []).append(f"{p['name']} {p['version']} ({name})")
    w("\n## Licence and copyright texts\n")
    for body, owners in by_text.items():
        w("\n### " + "; ".join(owners) + "\n\n```\n" + body + "\n```\n")
    missing = [p for p in rows if not texts(p)]
    if missing:
        w("\n## Crates that ship no licence file\n\n")
        for p in missing:
            w(f"- {p['name']} {p['version']}: {p['license']}"
              f"{', ' + p['repository'] if p.get('repository') else ''}\n")


if __name__ == "__main__":
    main()
